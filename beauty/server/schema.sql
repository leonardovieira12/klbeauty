CREATE TABLE IF NOT EXISTS kl_users (
 id TEXT PRIMARY KEY,
 email TEXT UNIQUE NOT NULL,
 password_hash TEXT NOT NULL,
 is_admin BOOLEAN NOT NULL DEFAULT FALSE,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS kl_sessions (
 token_hash TEXT PRIMARY KEY,
 user_id TEXT NOT NULL REFERENCES kl_users(id) ON DELETE CASCADE,
 expires TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS kl_sessions_expires_idx ON kl_sessions(expires);
CREATE TABLE IF NOT EXISTS kl_salons (
 id TEXT PRIMARY KEY,
 owner TEXT NOT NULL REFERENCES kl_users(id),
 name TEXT NOT NULL,
 state JSONB NOT NULL,
 version INTEGER NOT NULL DEFAULT 0,
 updated TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS kl_salons_owner_idx ON kl_salons(owner);
CREATE TABLE IF NOT EXISTS kl_login_limits (
 key TEXT PRIMARY KEY,
 attempts INTEGER NOT NULL,
 reset_at TIMESTAMPTZ NOT NULL
);
